from hashlib import md5
from pathlib import Path

from PIL import Image, ImageChops, ImageFilter, ImageOps, ImageStat


ROOT = Path(__file__).resolve().parents[1]
SOURCE_DIR = ROOT / "tree" / "photos-originals"
OUTPUT_DIR = ROOT / "tree" / "posts" / "img"
COLOR_DIR = OUTPUT_DIR / "color"
PHOTOS_JS = ROOT / "tree" / "src" / "photos.js"
SLUGS = {
    "ME2": "me-1",
    "1337": "ctf-1337",
    "AISBOARD": "ais-board",
    "AISSECRETARY": "ais-secretary",
    "GoogleDevfest": "google-devfest",
    "OMNETS": "om-nets",
}


def main():
    if not SOURCE_DIR.is_dir():
        raise FileNotFoundError(f"Photo source directory not found: {SOURCE_DIR}")

    input_files = {path.stem: path for path in SOURCE_DIR.iterdir() if path.is_file()}
    unexpected = sorted(set(input_files) - set(SLUGS))
    missing = sorted(set(SLUGS) - set(input_files))
    if missing:
        raise ValueError(f"Missing photos: {missing}")
    if unexpected:
        print(f"Ignoring unregistered photo originals: {', '.join(unexpected)}")

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    COLOR_DIR.mkdir(parents=True, exist_ok=True)
    manifest = {}
    warnings = []
    rows = []

    for original_name, slug in SLUGS.items():
        with Image.open(input_files[original_name]) as source:
            image = ImageOps.exif_transpose(source).convert("RGB")

        original_size = image.size
        if image.width > 760:
            final_width = 760
            final_height = round(image.height * final_width / image.width)
            image = image.resize((final_width, final_height), Image.Resampling.LANCZOS)
        else:
            final_width, final_height = image.size
            image = image.copy()
            warnings.append(f"{slug}: source is narrower than 760 px; kept its original width.")
        if final_width < 600:
            warnings.append(f"{slug}: final width is below 600 px ({final_width} px).")

        raw_gray = image.convert("L")
        if ImageStat.Stat(raw_gray).mean[0] < 40:
            warnings.append(f"{slug}: source appears very dark (mean luminance below 40/255).")
        laplacian = raw_gray.filter(
            ImageFilter.Kernel((3, 3), [0, 1, 0, 1, -4, 1, 0, 1, 0], scale=1, offset=128)
        )
        if ImageStat.Stat(laplacian).var[0] < 100:
            warnings.append(f"{slug}: may be blurry or low-detail (low Laplacian variance).")

        gray = ImageOps.autocontrast(raw_gray, cutoff=1)
        gray_rgb = Image.merge("RGB", (gray, gray, gray))
        gray_path = OUTPUT_DIR / f"{slug}.jpg"
        color_path = COLOR_DIR / f"{slug}.jpg"
        gray_rgb.save(gray_path, format="JPEG", quality=85)
        image.save(color_path, format="JPEG", quality=80)

        with Image.open(gray_path) as saved_gray:
            channels = saved_gray.convert("RGB").split()
            if any(ImageChops.difference(channels[0], channel).getbbox() for channel in channels[1:]):
                raise ValueError(f"Grayscale JPEG channels differ for {gray_path}")

        version = md5(gray_path.read_bytes()).hexdigest()[:10]
        manifest[slug] = {"w": final_width, "h": final_height, "v": version}
        rows.append((slug, original_size, (final_width, final_height)))

    lines = ["// Generated by tools/process-photos.py.", "export const photos = {"]
    for slug, info in manifest.items():
        lines.append(f'  "{slug}": {{ w: {info["w"]}, h: {info["h"]}, v: "{info["v"]}" }},')
    lines.append("};")
    PHOTOS_JS.write_text("\n".join(lines) + "\n", encoding="utf-8")

    print(f"{'Slug':<18} {'Original size':<18} Final size")
    for slug, original_size, final_size in rows:
        print(f"{slug:<18} {original_size[0]}x{original_size[1]:<13} {final_size[0]}x{final_size[1]}")
    if warnings:
        print("\nWarnings:")
        for warning in warnings:
            print(f"- {warning}")


if __name__ == "__main__":
    main()
